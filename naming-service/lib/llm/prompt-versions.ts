/**
 * 모든 프롬프트 버전
 */
export const PROMPT_VERSIONS: PromptVersion[] = [PROMPT_V1, PROMPT_V2]

/**
 * 활성화된 프롬프트 가져오기
 */
export function getActivePrompt(): PromptVersion {
  const active = PROMPT_VERSIONS.find(v => v.isActive)
  if (!active) {
    throw new Error('활성화된 프롬프트가 없습니다')
  }
  return active
}

/**
 * 특정 버전 프롬프트 가져오기
 */
export function getPromptVersion(version: string): PromptVersion | undefined {
  return PROMPT_VERSIONS.find(v => v.version === version)
}

/**
 * 최신 프롬프트 가져오기
 */
export function getLatestPrompt(): PromptVersion {
  return PROMPT_VERSIONS[PROMPT_VERSIONS.length - 1]
}
